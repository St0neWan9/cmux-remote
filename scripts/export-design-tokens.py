#!/usr/bin/env python3
"""Export shared product tokens to the static website."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
tokens = json.loads((root / "design/tokens.json").read_text())


def block(selector, values):
    return selector + " {\n" + "\n".join(f"  --{key}: {value};" for key, value in values.items()) + "\n}\n"


shared = dict(tokens["palette"])
for name in ("spacing", "radius", "size", "layout"):
    prefix = "space" if name == "spacing" else name
    shared.update({prefix + "-" + k: v for k, v in tokens[name].items()})
shared.update(tokens["typography"])
device = tokens["devices"]
shared["device-width-ratio"] = device["mac-width-mm"] / device["iphone-width-mm"]
shared["phone-source-width"] = str(device["phone-source-width-px"]) + "px"
shared["phone-source-height"] = str(device["phone-source-width-px"] * device["iphone-height-mm"] / device["iphone-width-mm"]) + "px"
shared["phone-aspect-ratio"] = device["iphone-width-mm"] / device["iphone-height-mm"]
css = "/* Generated by scripts/export-design-tokens.py from design/tokens.json. */\n"
css += block(":root", {**shared, **tokens["themes"]["light"]})
css += block('[data-theme="dark"]', tokens["themes"]["dark"])
css += block('[data-theme="light"]', tokens["themes"]["light"])
(root / "website/tokens.css").write_text(css)
print("Exported website/tokens.css")
